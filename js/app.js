window.AeroApp = (function () {
  const state = {
    acType: 'split',
    power: true,
    setpoint: 21.0,
    mode: 'COOL',
    fanSpeed: 3,
    louverAngle: 45,
    protocol: 'RMT_IR',
    ecoAi: true,
    xray: false,
    cfd: true,
    fault: 'normal',
    tempIn: 26.8,
    tempOut: 14.2,
    rh: 54
  };

  function init() {
    window.AeroTwin3D.init('canvas-container');
    updateGeneratedHeader();
    appendTerminalPacket('BOOT_SYNC');
    setInterval(runTelemetryCycle, 1500);
  }

  function runTelemetryCycle() {
    if (!state.power) {
      document.getElementById('val-power').textContent = '4 W';
      document.getElementById('val-current').textContent = '(0.02 A)';
      return;
    }

    const jitter = (Math.random() - 0.5) * 0.25;
    let supplyBase = state.setpoint - 6.8;

    if (state.fault === 'low_freon') {
      supplyBase = state.tempIn - 3.1; // Poor Delta-T
    } else if (state.fault === 'clogged_filter') {
      supplyBase = state.setpoint - 5.2;
    }

    const tIn = +(state.tempIn + jitter).toFixed(1);
    const tOut = +(supplyBase + jitter).toFixed(1);
    const deltaT = +(tIn - tOut).toFixed(1);

    document.getElementById('val-temp-in').textContent = `${tIn}°C`;
    document.getElementById('val-temp-out').textContent = `${tOut}°C`;
    document.getElementById('val-delta-t').textContent = `${deltaT}°C`;

    // Electrical & Vibration calculation
    let watts = 720 + (24 - state.setpoint) * 45 + state.fanSpeed * 22;
    if (state.ecoAi) watts *= 0.82;
    if (state.fault === 'clogged_filter') watts *= 1.24;

    const amps = (watts / 221.4).toFixed(2);
    const vib = state.fault === 'normal' ? (1.1 + Math.random() * 0.18).toFixed(2) : (3.45 + Math.random() * 0.4).toFixed(2);

    document.getElementById('val-power').textContent = `${Math.round(watts)} W`;
    document.getElementById('val-current').textContent = `(${amps} A)`;
    document.getElementById('val-vib').textContent = `${vib} mm/s`;
  }

  function buildProtocolHexFrame(triggerReason) {
    const tempByte = Math.round(state.setpoint * 2).toString(16).toUpperCase().padStart(2, '0');
    const fanByte = `0${state.fanSpeed}`;
    const pwrByte = state.power ? '01' : '00';

    if (state.protocol === 'RMT_IR') {
      return `11 DA 27 00 C5 ${pwrByte} ${tempByte} ${fanByte} A0 CS`;
    } else if (state.protocol === 'MODBUS_RS485') {
      return `01 06 00 02 ${pwrByte} ${tempByte} CRC16`;
    } else {
      return `FC 41 01 30 10 ${pwrByte} ${tempByte} ${fanByte} CHK`;
    }
  }

  function appendTerminalPacket(actionLabel) {
    const log = document.getElementById('terminal-log');
    if (!log) return;
    const now = new Date().toLocaleTimeString('id-ID', { hour12: false });
    const hex = buildProtocolHexFrame(actionLabel);
    const entry = document.createElement('div');
    entry.innerHTML = `<span class="text-slate-500">[${now}]</span> <span class="text-cyan-400">${actionLabel}</span> &rarr; <span>${hex}</span>`;
    log.prepend(entry);
  }

  function updateGeneratedHeader() {
    const host = document.getElementById('cfg-hostname').value;
    const mqtt = document.getElementById('cfg-mqtt').value;
    const vendor = document.getElementById('cfg-vendor').value;
    const wdt = document.getElementById('cfg-wdt').value;

    const code = `// Auto-Generated by AeroTwin C3 Provisioning Engine
// Target MCU: ESP32-C3 SuperMini (RISC-V 160MHz)
#pragma once

#define AERO_NODE_HOSTNAME     "${host}"
#define AERO_MQTT_BROKER_URI   "${mqtt}"
#define AERO_AC_PROTOCOL       PROTO_${vendor}
#define AERO_HW_WDT_TIMEOUT_S  ${wdt}

// ESP32-C3 SuperMini Fixed Pinout Mapping
#define PIN_ADC_SCT013         0   // GPIO0 - Current Sensor CT
#define PIN_ADC_DRAIN_LEVEL    1   // GPIO1 - Condensate Pan Float
#define PIN_ONEWIRE_DS18B20    2   // GPIO2 - Supply & Return Temp
#define PIN_RMT_IR_RX          3   // GPIO3 - 38kHz Carrier Sniffer
#define PIN_RMT_IR_TX          4   // GPIO4 - High-Power IR Blaster
#define PIN_RS485_DERE         5   // GPIO5 - MAX485 Direction Control
#define PIN_RS485_TX           6   // GPIO6 - Modbus RTU TX
#define PIN_RS485_RX           7   // GPIO7 - Modbus RTU RX
#define PIN_I2C_SDA            8   // GPIO8 - MEMS & BME280 SDA
#define PIN_I2C_SCL            9   // GPIO9 - MEMS & BME280 SCL`;

    document.getElementById('code-preview').textContent = code;
  }

  window.addEventListener('DOMContentLoaded', init);

  return {
    getState: () => state,

    setAcType: function (type) {
      state.acType = type;
      window.AeroTwin3D.setAcType(type);
      document.querySelectorAll('.ac-type-btn').forEach((btn) => btn.classList.remove('active'));
      const activeBtn = document.getElementById(`btn-type-${type}`);
      if (activeBtn) activeBtn.classList.add('active');
      appendTerminalPacket(`ARCH_${type.toUpperCase()}`);
    },

    togglePower: function () {
      state.power = !state.power;
      const btn = document.getElementById('btn-power');
      const status = document.getElementById('status-ac-power');
      if (state.power) {
        btn.className = 'w-10 h-10 rounded-xl bg-emerald-500 text-slate-950 flex items-center justify-center shadow-lg shadow-emerald-500/20 cursor-pointer';
        status.textContent = 'STATUS: RUNNING NORMAL';
        status.className = 'text-xs font-mono text-emerald-400';
      } else {
        btn.className = 'w-10 h-10 rounded-xl bg-rose-500/20 border border-rose-500/40 text-rose-400 flex items-center justify-center cursor-pointer';
        status.textContent = 'STATUS: STANDBY OFF';
        status.className = 'text-xs font-mono text-rose-400';
      }
      appendTerminalPacket(state.power ? 'PWR_ON' : 'PWR_OFF');
    },

    adjustTemp: function (delta) {
      state.setpoint = Math.min(30, Math.max(16, +(state.setpoint + delta).toFixed(1)));
      document.getElementById('val-setpoint').textContent = `${state.setpoint.toFixed(1)}°C`;
      appendTerminalPacket(`SET_${state.setpoint}C`);
    },

    setMode: function (mode) {
      state.mode = mode;
      document.querySelectorAll('.mode-btn').forEach((b) => {
        b.className = 'mode-btn py-2 rounded-lg border border-slate-800 bg-slate-900 text-slate-400';
      });
      const active = document.getElementById(`mode-${mode}`);
      if (active) {
        active.className = 'mode-btn active py-2 rounded-lg border border-cyan-500/50 bg-cyan-500/20 text-cyan-300 font-semibold';
      }
      appendTerminalPacket(`MODE_${mode}`);
    },

    setFanSpeed: function (val) {
      state.fanSpeed = Number(val);
      const labels = { 1: 'LOW (680 RPM)', 2: 'MED (960 RPM)', 3: 'HIGH (1,280 RPM)', 4: 'TURBO (1,540 RPM)' };
      document.getElementById('val-fan-rpm').textContent = labels[state.fanSpeed];
      appendTerminalPacket(`FAN_LVL_${state.fanSpeed}`);
    },

    setLouverAngle: function (deg) {
      state.louverAngle = Number(deg);
      document.getElementById('val-louver').textContent = `${deg}° (Motorized)`;
      appendTerminalPacket(`SWING_${deg}DEG`);
    },

    setProtocol: function (proto) {
      state.protocol = proto;
      document.getElementById('tx-proto-badge').textContent = proto;
      appendTerminalPacket('PROTO_SWITCH');
    },

    toggleEcoAi: function (checked) {
      state.ecoAi = checked;
      document.getElementById('val-eco-saved').textContent = checked ? '28.4% (-4.2 kgCO₂)' : '0.0% (Bypassed)';
      appendTerminalPacket(checked ? 'ECO_AI_ON' : 'ECO_AI_OFF');
    },

    setFaultMode: function (faultKey) {
      state.fault = faultKey;
      document.querySelectorAll('.fault-btn').forEach((b) => {
        b.className = 'fault-btn py-1.5 px-2 rounded border border-slate-800 bg-slate-900 text-slate-400';
      });
      const active = document.getElementById(`fault-${faultKey}`);
      if (active) {
        active.className = 'fault-btn active py-1.5 px-2 rounded border border-amber-500/50 bg-amber-500/20 text-amber-300';
      }

      if (faultKey === 'clogged_filter') {
        document.getElementById('val-filter').textContent = '86% (Kritis)';
        document.getElementById('bar-filter').style.width = '86%';
        document.getElementById('bar-filter').className = 'h-full bg-amber-400 transition-all';
      } else {
        document.getElementById('val-filter').textContent = '18% (Bersih)';
        document.getElementById('bar-filter').style.width = '18%';
        document.getElementById('bar-filter').className = 'h-full bg-emerald-400 transition-all';
      }

      if (faultKey === 'drain_overflow') {
        document.getElementById('val-drain').textContent = '94% MELUAP!';
        document.getElementById('bar-drain').style.width = '94%';
        document.getElementById('bar-drain').className = 'h-full bg-rose-500 transition-all';
      } else {
        document.getElementById('val-drain').textContent = '24% Normal';
        document.getElementById('bar-drain').style.width = '24%';
        document.getElementById('bar-drain').className = 'h-full bg-cyan-400 transition-all';
      }

      appendTerminalPacket(`SIM_${faultKey.toUpperCase()}`);
    },

    toggleXray: function () {
      state.xray = !state.xray;
      window.AeroTwin3D.setXray(state.xray);
      document.getElementById('btn-xray').querySelector('span:last-child').textContent = `X-Ray CAD Mode: ${state.xray ? 'ON' : 'OFF'}`;
    },

    toggleCfd: function () {
      state.cfd = !state.cfd;
      window.AeroTwin3D.setCfd(state.cfd);
      document.getElementById('btn-cfd').querySelector('span:last-child').textContent = `Partikel CFD: ${state.cfd ? 'ON' : 'OFF'}`;
    },

    sendManualCommandSync: function () {
      appendTerminalPacket('MANUAL_SYNC_TX');
    },

    toggleSetupModal: function (show) {
      const modal = document.getElementById('modal-setup');
      modal.classList.toggle('hidden', !show);
    },

    updateGeneratedHeader,

    copyConfigHeader: function () {
      const code = document.getElementById('code-preview').textContent;
      navigator.clipboard.writeText(code);
      document.getElementById('ota-status').textContent = 'Header Disalin ke Clipboard!';
    },

    triggerRemoteOtaPush: function () {
      const bar = document.getElementById('ota-bar');
      const status = document.getElementById('ota-status');
      bar.style.width = '35%';
      status.textContent = 'Mengirim Paket RPC ke ESP32-C3...';
      setTimeout(() => {
        bar.style.width = '75%';
        status.textContent = 'Menulis Partisi NVS & Verifikasi CRC32...';
      }, 600);
      setTimeout(() => {
        bar.style.width = '100%';
        status.textContent = 'Sukses! Node ESP32-C3 SuperMini Aktif.';
        appendTerminalPacket('OTA_NVS_COMMITTED');
      }, 1300);
    },

    switchMobileView: function (tab) {
      const pTel = document.getElementById('panel-telemetry');
      const pCtrl = document.getElementById('panel-control');
      pTel.classList.add('hidden');
      pCtrl.classList.add('hidden');

      if (tab === 'telemetry') pTel.classList.remove('hidden');
      if (tab === 'control') pCtrl.classList.remove('hidden');
    }
  };
})();
